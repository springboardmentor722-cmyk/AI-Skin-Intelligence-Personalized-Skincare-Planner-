@router.post("/assessment/evaluate", response_model=AssessmentOut, status_code=201)
def evaluate(body: AssessmentIn, request: Request,
             user: User = Depends(require("assessment.create")),
             db: Session = Depends(get_db)):
    """Run the assessment + scoring engines, persist a snapshot, build the routine."""
    data = body.model_dump()
    supplied = {k: v for k, v in data.items() if v not in (None, "", {}, [])}

    # Fill any gap in the wizard payload from the stored Milestone 1 profile, so an
    # assessment is never penalised for data the user has already given us.
    profile = db.scalar(select(SkinProfile).where(SkinProfile.user_id == user.id))
    if profile:
        for field in ("age", "gender", "skin_type", "concerns", "sensitivities", "allergies"):
            if not data.get(field):
                data[field] = getattr(profile, field, None)

    latest = _latest_lifestyle(db, user.id)
    if latest:
        for field in ("sleep_hours", "water_intake_l", "exercise_minutes",
                      "stress_level", "environment_exposure"):
            if data.get(field) is None:
                data[field] = getattr(latest, field, None)

    concerns, breakdown, recommendations = _run_engines(db, user, data)
    assessment = _persist_assessment(db, user, data, concerns, breakdown, recommendations)

    # Keep the Milestone 1 skin profile in step with what the wizard collected.
    if profile:
        for field in ("age", "gender", "skin_type", "concerns", "sensitivities", "allergies"):
            if supplied.get(field):
                setattr(profile, field, supplied[field])

    # Persist today's lifestyle numbers into Milestone 1's own table too.
    if any(data.get(f) is not None for f in ("sleep_hours", "water_intake_l")):
        today_log = db.scalar(select(LifestyleLog).where(
            LifestyleLog.user_id == user.id, LifestyleLog.log_date == date.today()))
        if not today_log:
            today_log = LifestyleLog(user_id=user.id, log_date=date.today())
            db.add(today_log)
        for field in ("sleep_hours", "water_intake_l", "exercise_minutes",
                      "stress_level", "environment_exposure"):
            if data.get(field) is not None:
                setattr(today_log, field, data[field])

    if body.generate_routine:
        plan = routine_engine.generate_routine(
            skin_type=data.get("skin_type"),
            concerns=concerns,
            sensitivities=data.get("sensitivities"),
            db=db,
        )
        _save_routine(db, user, assessment, plan)

    notify(db, user.id, "Skin assessment complete",
           f"Your Skin Health Score is {breakdown['overall_score']} "
           f"({scoring_engine.score_band(breakdown['overall_score'])}).", "routine")
    audit(db, request, user, "assessment.evaluate", "skin_assessment", assessment.id,
          new_value={"score": breakdown["overall_score"],
                     "primary_concern": assessment.primary_concern})
    db.commit()
    db.refresh(assessment)
    return _assessment_out(assessment, routine_logs.storage_backend())


