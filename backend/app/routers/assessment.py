@router.get("/routine", response_model=RoutinePlanOut)
def get_routine(user: User = Depends(require("routine.read_own")),
                db: Session = Depends(get_db)):
    """The active plan, with today's completion state merged in from routine_logs."""
    return _routine_plan(db, user)


def _routine_plan(db: Session, user: User) -> RoutinePlanOut:
    rows = db.scalars(select(SkincareRoutine).where(
        SkincareRoutine.user_id == user.id,
        SkincareRoutine.is_active.is_(True),
    ).order_by(SkincareRoutine.time_of_day, SkincareRoutine.step_number)).all()

    today_log = routine_logs.get_log(db, user.id, date.today())
    done_ids = {s["routine_step_id"] for s in today_log.get("completed_steps", [])}

    plan = RoutinePlanOut()
    if rows:
        plan.assessment_id = rows[0].assessment_id
        plan.generated_at = rows[0].created_at

    daily_total = 0
    daily_done = 0
    for r in rows:
        step = RoutineStepOut.model_validate(r)
        step.completed = r.id in done_ids
        getattr(plan, r.time_of_day).append(step)
        if r.time_of_day in DAILY_PHASES:
            daily_total += 1
            daily_done += 1 if step.completed else 0

    plan.total_daily_steps = daily_total
    plan.completed_today = daily_done
    plan.completion_percent = round((daily_done / daily_total) * 100, 1) if daily_total else 0.0
    return plan


