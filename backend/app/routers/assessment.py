# GET /api/v1/assessment/score          (spec Step 3.2)
# ---------------------------------------------------------------------------
@router.get("/assessment/score", response_model=AssessmentOut)
def latest_score(recalculate: bool = False, request: Request = None,
                 user: User = Depends(require("assessment.read_own")),
                 db: Session = Depends(get_db)):
    """The user's latest score breakdown.

    `?recalculate=true` re-runs the engine against current data (so today's
    checklist ticks are reflected) and saves a fresh historical snapshot.
    """
    if not recalculate:
        row = db.scalar(select(SkinAssessment)
                        .where(SkinAssessment.user_id == user.id)
                        .order_by(desc(SkinAssessment.created_at)).limit(1))
        if row:
            return _assessment_out(row, routine_logs.storage_backend())

    # No assessment yet (or a recalculation was requested): build one from
    # whatever Milestone 1 data we already hold.
    profile = db.scalar(select(SkinProfile).where(SkinProfile.user_id == user.id))
    latest = _latest_lifestyle(db, user.id)
    if not profile and not latest:
        raise HTTPException(status.HTTP_404_NOT_FOUND,
                            "No assessment yet — complete the skin assessment to get your score.")

    data = {
        "age": getattr(profile, "age", None),
        "skin_type": getattr(profile, "skin_type", None),
        "concerns": getattr(profile, "concerns", None),
        "sensitivities": getattr(profile, "sensitivities", None),
        "sleep_hours": getattr(latest, "sleep_hours", None),
        "water_intake_l": getattr(latest, "water_intake_l", None),
        "exercise_minutes": getattr(latest, "exercise_minutes", None),
        "stress_level": getattr(latest, "stress_level", None),
        "environment_exposure": getattr(latest, "environment_exposure", None),
    }
    concerns, breakdown, recommendations = _run_engines(db, user, data)
    assessment = _persist_assessment(db, user, data, concerns, breakdown, recommendations)
    audit(db, request, user, "assessment.score", "skin_assessment", assessment.id,
          new_value={"score": breakdown["overall_score"], "recalculated": recalculate})
    db.commit()
    db.refresh(assessment)
    return _assessment_out(assessment, routine_logs.storage_backend())


@router.get("/assessment/history", response_model=list[AssessmentOut])
def history(limit: int = 30,
            user: User = Depends(require("assessment.read_own")),
            db: Session = Depends(get_db)):
    """Every historical snapshot — powers the progress chart."""
    rows = db.scalars(select(SkinAssessment)
                      .where(SkinAssessment.user_id == user.id)
                      .order_by(desc(SkinAssessment.created_at))
                      .limit(min(limit, 200))).all()
    return [_assessment_out(r) for r in rows]


