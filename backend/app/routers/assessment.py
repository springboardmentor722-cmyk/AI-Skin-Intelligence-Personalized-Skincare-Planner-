"""Milestone 2 API — /api/v1/assessment/* and /api/v1/routine/*

Every route is protected by the Milestone 1 JWT layer (`require(...)`), reuses the
Milestone 1 session, audit and notification helpers, and adds no new auth of its own.
"""
from __future__ import annotations

import json
from datetime import date

from fastapi import APIRouter, Depends, HTTPException, Request, status
from sqlalchemy import desc, select
from sqlalchemy.orm import Session

from ..database import get_db
from ..deps import audit, notify, require
from ..models import (LifestyleLog, ProgressEntry, SkinAssessment, SkinProfile,
                      SkincareRoutine, User)
from ..schemas import (AssessmentIn, AssessmentOut, RoutineGenerateIn, RoutineLogOut,
                       RoutinePlanOut, RoutineStepOut, StepCompletionIn)
from ..services import assessment_engine, routine_engine, routine_logs, scoring_engine

router = APIRouter(prefix="/v1", tags=["milestone-2"])

DAILY_PHASES = ("AM", "PM")   # what counts toward daily compliance


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------
def _latest_lifestyle(db: Session, user_id: int) -> LifestyleLog | None:
    return db.scalar(select(LifestyleLog).where(LifestyleLog.user_id == user_id)
                     .order_by(desc(LifestyleLog.log_date)).limit(1))


def _expected_daily_steps(db: Session, user_id: int) -> int:
    """How many AM+PM steps the user's active routine expects each day."""
    return len(db.scalars(select(SkincareRoutine).where(
        SkincareRoutine.user_id == user_id,
        SkincareRoutine.is_active.is_(True),
        SkincareRoutine.time_of_day.in_(DAILY_PHASES),
    )).all())


def _run_engines(db: Session, user: User, data: dict) -> tuple[list[dict], dict, list[str]]:
    """Assessment -> scoring -> recommendations. The heart of Milestone 2."""
    concerns = assessment_engine.identify_skin_concerns(data)

    expected = _expected_daily_steps(db, user.id)
    completed, expected_total = routine_logs.consistency_last_7_days(db, user.id, expected)

    breakdown = scoring_engine.score_breakdown(
        concerns=concerns,
        sleep_hours=data.get("sleep_hours"),
        water_intake_l=data.get("water_intake_l"),
        completed_steps=completed,
        expected_steps=expected_total,
        environment_exposure=data.get("environment_exposure"),
        uses_sunscreen=data.get("uses_sunscreen", True),
        exercise_minutes=data.get("exercise_minutes"),
        stress_level=data.get("stress_level"),
        smokes=data.get("smokes", False),
    )

    recommendations = assessment_engine.generate_recommendations(
        concerns=concerns,
        skin_type=data.get("skin_type"),
        breakdown=breakdown,
        sleep_hours=data.get("sleep_hours"),
        water_intake_l=data.get("water_intake_l"),
        consistency=breakdown["breakdown"]["consistency"]["score"],
    )
    return concerns, breakdown, recommendations


def _persist_assessment(db: Session, user: User, data: dict, concerns: list[dict],
                        breakdown: dict, recommendations: list[str]) -> SkinAssessment:
    """Write the historical snapshot into skin_assessments (spec Step 3.2)."""
    b = breakdown["breakdown"]
    row = SkinAssessment(
        user_id=user.id,
        overall_score=breakdown["overall_score"],
        condition_score=b["skin_condition"]["score"],
        lifestyle_score=b["lifestyle"]["score"],
        consistency_score=b["consistency"]["score"],
        sleep_score=b["sleep"]["score"],
        hydration_score=b["hydration"]["score"],
        detected_concerns=json.dumps(concerns),
        primary_concern=assessment_engine.primary_concern(concerns),
        skin_type=data.get("skin_type"),
        recommendations=json.dumps(recommendations),
    )
    db.add(row)
    db.flush()

    # Feed the Milestone 1 progress chart so the two systems stay in step.
    db.add(ProgressEntry(
        user_id=user.id,
        entry_date=date.today(),
        skin_score=int(round(breakdown["overall_score"])),
        hydration=int(round(b["hydration"]["score"])),
        notes="Auto-generated by the Milestone 2 assessment engine",
    ))
    return row


def _save_routine(db: Session, user: User, assessment: SkinAssessment,
                  plan: dict[str, list[dict]]) -> None:
    """Replace the user's active plan with the newly generated one."""
    for old in db.scalars(select(SkincareRoutine).where(
            SkincareRoutine.user_id == user.id,
            SkincareRoutine.is_active.is_(True))).all():
        old.is_active = False

    for phase, steps in plan.items():
        for s in steps:
            db.add(SkincareRoutine(
                user_id=user.id,
                assessment_id=assessment.id,
                time_of_day=phase,
                step_number=s["step_number"],
                step_category=s["step_category"],
                instruction=s.get("instruction"),
                is_active=True,
            ))


def _assessment_out(row: SkinAssessment, storage: str = "") -> AssessmentOut:
    """Build the response.

    Constructed field-by-field rather than via model_validate, because the ORM
    stores `detected_concerns` / `recommendations` as JSON *strings* — they must
    be parsed into real lists before Pydantic sees them.
    """
    return AssessmentOut(
        id=row.id,
        user_id=row.user_id,
        overall_score=row.overall_score,
        band=scoring_engine.score_band(row.overall_score),
        skin_type=row.skin_type,
        primary_concern=row.primary_concern,
        detected_concerns=json.loads(row.detected_concerns or "[]"),
        recommendations=json.loads(row.recommendations or "[]"),
        created_at=row.created_at,
        consistency_source=storage,
        breakdown={
            "skin_condition": {"score": row.condition_score, "weight": scoring_engine.W_CONDITION,
                               "contribution": round(row.condition_score * scoring_engine.W_CONDITION, 2)},
            "lifestyle": {"score": row.lifestyle_score, "weight": scoring_engine.W_LIFESTYLE,
                          "contribution": round(row.lifestyle_score * scoring_engine.W_LIFESTYLE, 2)},
            "sleep": {"score": row.sleep_score, "weight": scoring_engine.W_SLEEP,
                      "contribution": round(row.sleep_score * scoring_engine.W_SLEEP, 2)},
            "consistency": {"score": row.consistency_score, "weight": scoring_engine.W_CONSISTENCY,
                            "contribution": round(row.consistency_score * scoring_engine.W_CONSISTENCY, 2)},
            "hydration": {"score": row.hydration_score, "weight": scoring_engine.W_HYDRATION,
                          "contribution": round(row.hydration_score * scoring_engine.W_HYDRATION, 2)},
        },
    )


