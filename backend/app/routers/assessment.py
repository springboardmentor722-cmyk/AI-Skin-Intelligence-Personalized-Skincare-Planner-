@router.post("/routine/generate", response_model=RoutinePlanOut, status_code=201)
def generate(body: RoutineGenerateIn, request: Request,
             user: User = Depends(require("routine.generate")),
             db: Session = Depends(get_db)):
    """(Re)generate the AM/PM/Weekly/Seasonal plan from the latest assessment."""
    assessment = db.scalar(select(SkinAssessment)
                           .where(SkinAssessment.user_id == user.id)
                           .order_by(desc(SkinAssessment.created_at)).limit(1))
    if not assessment:
        raise HTTPException(status.HTTP_400_BAD_REQUEST,
                            "Run an assessment first — the routine is built from its results.")

    profile = db.scalar(select(SkinProfile).where(SkinProfile.user_id == user.id))
    concerns = json.loads(assessment.detected_concerns or "[]")
    skin_type = body.skin_type or assessment.skin_type or getattr(profile, "skin_type", None)

    plan = routine_engine.generate_routine(
        skin_type=skin_type,
        concerns=concerns,
        sensitivities=getattr(profile, "sensitivities", None),
        db=db,
    )
    _save_routine(db, user, assessment, plan)
    audit(db, request, user, "routine.generate", "skincare_routine", assessment.id,
          new_value={"skin_type": skin_type, "steps": sum(len(v) for v in plan.values())})
    db.commit()
    return _routine_plan(db, user)


