@router.post("/routine/complete", response_model=RoutinePlanOut)
def complete_step(body: StepCompletionIn,
                  user: User = Depends(require("routine.log_own")),
                  db: Session = Depends(get_db)):
    """Tick or untick one routine step — writes straight into routine_logs."""
    step = db.get(SkincareRoutine, body.routine_step_id)
    if not step or step.user_id != user.id:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Routine step not found")

    log_date = body.log_date or date.today()
    if log_date > date.today():
        raise HTTPException(status.HTTP_400_BAD_REQUEST, "Cannot log a step for a future date")

    routine_logs.toggle_step(db, user.id, log_date, body.routine_step_id, body.completed)
    return _routine_plan(db, user)


@router.get("/routine/log", response_model=RoutineLogOut)
def get_routine_log(on: date | None = None,
                    user: User = Depends(require("routine.read_own")),
                    db: Session = Depends(get_db)):
    """The raw routine_logs document for a day — shows exactly what is stored."""
    doc = routine_logs.get_log(db, user.id, on or date.today())
    doc["storage"] = routine_logs.storage_backend()
    return doc


@router.post("/routine/log/metrics", response_model=RoutineLogOut)
def log_metrics(water_intake_ml: int | None = None, sleep_hours: float | None = None,
                user: User = Depends(require("routine.log_own")),
                db: Session = Depends(get_db)):
    """Record today's water and sleep into the same routine_logs document."""
    doc = routine_logs.update_metrics(db, user.id, date.today(),
                                      water_intake_ml, sleep_hours)
    doc["storage"] = routine_logs.storage_backend()
    return doc
